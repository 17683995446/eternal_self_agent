"""
全局常量定义 — 公理固化

设计意图: 所有系统行为参数的唯一来源，任何魔法数字必须在此定义。
公理溯源:
  - LOOP_DELAY        ← 存续公理: 控CPU、防卡死、稳态运行
  - EVOLVE_STEP       ← 自驱公理: 周期性触发知识进化
  - KG_SAVE_PATH      ← 记忆公理: 唯一持久化文件入口
  - TASK_QUEUE_MAX    ← 资源守恒公理: 限制任务池上限，杜绝无限膨胀
"""

from __future__ import annotations

import os

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 存续公理: 主循环节拍
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
LOOP_DELAY: float = 0.3
"""主循环每次迭代间隔(秒)。控制CPU占用，防止空转卡死。"""

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 自驱公理: 进化触发步数
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
EVOLVE_STEP: int = 50
"""每执行N次循环后，自动触发一次知识精简与进化。"""

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 记忆公理: 持久化路径
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 默认存储在项目 data/ 目录下，支持环境变量覆盖
_DATA_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data"
)
DATA_DIR: str = os.environ.get("ETERNAL_DATA_DIR", _DATA_DIR)
"""数据存储根目录。"""

KG_SAVE_PATH: str = os.path.join(DATA_DIR, "knowledge_graph.json")
"""知识图谱持久化文件路径（记忆公理唯一入口）。"""

TASK_QUEUE_SAVE_PATH: str = os.path.join(DATA_DIR, "task_queue.json")
"""任务队列持久化文件路径。"""

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 资源守恒公理: 任务池上限
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
TASK_QUEUE_MAX: int = 200
"""任务队列最大容量。超出时丢弃最低优先级任务，防止内存无限膨胀。"""

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 自驱公理: 知识推演阈值
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
DERIVE_WEIGHT_THRESHOLD: float = 0.2
"""知识推演时，只采信权重大于此值的关联。"""

TRIM_WEIGHT_THRESHOLD: float = 0.1
"""知识精简时，淘汰权重低于此值的关联。"""

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 存续公理: 自愈参数
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
SELF_REPAIR_DELAY: float = 1.0
"""异常自愈时休眠时间(秒)，避免快速重试风暴。"""

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 系统标识
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
SYSTEM_NAME: str = "eternal_self_agent"
VERSION: str = "0.1.0"
